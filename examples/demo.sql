-- Base entièrement fictive, réservée à la démonstration et aux tests.
CREATE TABLE demo_author (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name varchar(120) NOT NULL,
    password_hash text NOT NULL,
    mentor_id integer REFERENCES demo_author(id)
);
CREATE TABLE demo_article (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    author_id integer NOT NULL REFERENCES demo_author(id),
    reviewer_id integer REFERENCES demo_author(id),
    price numeric(12,2) NOT NULL,
    published boolean NOT NULL,
    uuid uuid NOT NULL,
    payload jsonb,
    binary_data bytea,
    published_at timestamptz,
    created_at timestamp NOT NULL,
    day date NOT NULL,
    large_number bigint NOT NULL,
    UNIQUE (title, author_id)
);
CREATE TABLE demo_profile (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id integer UNIQUE REFERENCES demo_author(id)
);
CREATE TABLE demo_passport (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id integer NOT NULL UNIQUE REFERENCES demo_author(id)
);
CREATE TABLE demo_tag (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text NOT NULL);
CREATE TABLE demo_article_tag (
    article_id integer NOT NULL REFERENCES demo_article(id),
    tag_id integer NOT NULL REFERENCES demo_tag(id),
    PRIMARY KEY (article_id, tag_id)
);
CREATE TABLE demo_follow (
    follower_id integer NOT NULL REFERENCES demo_author(id),
    followed_id integer NOT NULL REFERENCES demo_author(id),
    PRIMARY KEY (follower_id, followed_id)
);
CREATE TABLE demo_membership (
    author_id integer NOT NULL REFERENCES demo_author(id),
    tag_id integer NOT NULL REFERENCES demo_tag(id),
    note text NOT NULL,
    PRIMARY KEY (author_id, tag_id)
);
CREATE TABLE demo_translation (
    article_id integer NOT NULL REFERENCES demo_article(id),
    locale varchar(8) NOT NULL,
    title text NOT NULL,
    PRIMARY KEY (article_id, locale)
);
CREATE TABLE demo_region (country varchar(2) NOT NULL, code integer NOT NULL, PRIMARY KEY (country, code));
CREATE TABLE demo_office (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_country varchar(2) NOT NULL,
    region_code integer NOT NULL,
    FOREIGN KEY (region_country, region_code) REFERENCES demo_region(country, code),
    UNIQUE (region_country, region_code)
);
CREATE TABLE "odd table" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "first-name" text NOT NULL,
    first_name text NOT NULL,
    "class" text NOT NULL,
    "quote'column" text NOT NULL
);
CREATE TABLE odd_table (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
CREATE TABLE demo_serial (id serial PRIMARY KEY, text text NOT NULL);
